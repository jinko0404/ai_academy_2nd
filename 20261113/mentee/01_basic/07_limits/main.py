# 이 프로그램은 무엇을 하는가?
# ============================
# 누군가 작성한 답변 3개를 보고, 미리 정한 규칙에 따라 문제 이름을 붙인다.
# 예: 원본에는 "개인 폴더"라고 쓰여 있는데 답변에는 "공용 서버"라고 썼다면?
#     → 원본과 다르다고 표시한다.
# 실제 AI에게 답변을 요청하는 코드는 없다. 질문과 답변은 아래에 직접 적혀 있다.
#
# 전체 흐름
# 1. 원본 문장, 답변, 출처가 들어 있는 사례 3개 준비
#                         ↓
# 2. 사례를 하나씩 꺼내 아래 순서로 검사
#    출처 항목 자체가 없는가? ── 그렇다 → format(형식 누락)
#              │ 아니다
#              ↓
#    출처 항목은 있지만 비어 있는가? ── 그렇다 → evidence(근거 누락)
#              │ 아니다
#              ↓
#    답변 문자열이 원본 문자열과 다른가? ── 그렇다 → factual_mismatch(불일치)
#              │ 아니다
#              ↓
#             ok(이 예제의 검사 통과)
#                         ↓
# 3. 결과를 모음: F01=불일치 / F02=형식 누락 / F03=근거 누락
#                         ↓
# 4. review.json(데이터 보관용), review.md(사람이 읽을 문서)로 저장
#
# 수업에서 가져갈 개념 하나:
# 답변 내용이 맞는지, 필요한 항목이 있는지, 출처가 있는지는 서로 다른 문제이다.
# F02와 F03은 답변 문장이 원본과 같아도 각각 다른 이유로 검사에 걸린다.
#
# 이 코드의 한계도 알아 두자.
# 문자열을 비교할 뿐, 문장의 뜻을 이해해서 사실 여부를 판단하는 것은 아니다.
# 같은 뜻을 다르게 표현해도 서로 다른 문자열이면 불일치로 표시한다.
# 출처 이름이 있어도 실제로 존재하는 자료인지, 답변을 뒷받침하는지는 확인하지 않는다.
#
# 아래는 실행 준비이다. 분류 과정부터 보려면 def main():으로 내려가면 된다.
# Path는 파일을 저장할 위치를 다루는 도구이다.
from pathlib import Path
# sys는 파이썬 실행 환경을 설정할 때 쓰는 도구이다.
import sys

# __file__은 현재 main.py의 경로이다. resolve()는 전체 경로를 구한다.
# parent는 파일이 들어 있는 폴더이다. HERE는 07_limits 폴더를 가리킨다.
HERE = Path(__file__).resolve().parent
# 한 단계 위인 01_basic 폴더를 가리킨다. 여기에 common 폴더가 있다.
LEVEL_ROOT = HERE.parent
# 파이썬에게 이 폴더에서도 코드를 찾아보라고 알려준다.
# str()은 경로를 문자열로 바꾸고 insert(0, ...)은 목록 맨 앞에 넣는다.
sys.path.insert(0, str(LEVEL_ROOT))  # 어느 작업 폴더에서 실행해도 common 패키지를 찾습니다.
# 다른 파일에 만들어 둔 저장 함수 두 개를 가져온다.
# write_json은 데이터를 JSON으로, write_md는 글을 Markdown 문서로 저장한다.
from common.support import write_json, write_md

# 세 예시는 수업용으로 사람이 미리 설계한 사례입니다. 실제 자동 사실성 검사기가 아닙니다.
# [1단계] 검사할 사례를 준비한다.
# CASES는 사례들을 담은 리스트 [ ... ]이고, 안의 { ... } 하나가 사례 하나이다.
# 딕셔너리 { ... }는 "이름": 값 형태로 정보를 보관한다.
# id: 사례 번호 / question: 질문 / source: 비교 기준인 원본 문장 /
# answer: 검사할 답변 / sources: 답변에 붙인 출처 이름 목록.
# 특히 source(원본 문장)와 sources(출처 이름 목록)는 다른 항목이다.
CASES = [
    # F01: 출처 이름 K01은 있지만, 답변의 "공용 서버"가 원본의 "개인 폴더"와 다르다.
    {"id":"F01","question":"파일을 어디에 보관하나요?",
     "source":"실습 파일은 개인 폴더에 보관합니다.",
     "answer":"실습 파일은 공용 서버 폴더에 보관합니다.","sources":["K01"]},
    # F02: 답변 문장은 같지만 sources라는 항목 자체가 빠져 있다.
    {"id":"F02","question":"서버는 어디에서 실행하나요?",
     "source":"프로젝트 폴더에서 서버를 실행합니다.",
     "answer":"프로젝트 폴더에서 서버를 실행합니다."},
    # F03: sources 항목은 있다. 하지만 []이므로 출처 이름이 하나도 없다.
    {"id":"F03","question":"질문할 때 무엇을 함께 적나요?",
     "source":"오류 메시지와 시도한 작업을 함께 적습니다.",
     "answer":"오류 메시지와 시도한 작업을 함께 적습니다.","sources":[]},
]

# 아래 들여쓴 코드들을 main이라는 이름으로 묶는다.
# 맨 아래 main()에서 호출하면 이 안의 코드를 위에서 아래로 실행한다.
def main():

    # TODO D20-07-B01: 3개 답변에서 정해 둔 형태·근거·사실 불일치를 분류하세요.
    # 입력·대상: 제공된 F01/F02/F03 사례만 대상으로 분류합니다.
    # 완료 확인: outputs/review.json, review.md에서 사실 불일치/형식 누락/근거 누락을 확인합니다.
    # 주의: 사전 설계된 규칙 기반 점검이며 실제 생성형 AI의 진위 판정기가 아닙니다.
    # BEGIN D20-07-B01
    # [2단계] 검사 결과를 담을 빈 리스트를 만든다.
    # 나중에 [{"id": "F01", "kind": "factual_mismatch"}, ...]로 채워진다.
    issues = []
    # CASES에서 사례를 하나씩 꺼내 case라는 변수에 넣는다.
    # 첫 반복에는 F01의 딕셔너리 전체, 다음에는 F02, 마지막에는 F03이 들어온다.
    for case in CASES:
        # 첫 질문: "sources"라는 이름의 항목이 딕셔너리에 없는가?
        # 딕셔너리에 in을 쓰면 값이 아니라 항목 이름(키)이 있는지 확인한다.
        # not in은 "없다"라는 뜻이다. F02가 여기에 해당한다.
        if "sources" not in case:
            # kind는 이번 사례에 붙일 문제 이름이다. F02에서는 "format"을 저장한다.
            kind = "format"  # TODO: 필수 필드 자체가 없으면 "format"
        # elif는 "앞 조건에 해당하지 않으면 이것도 검사"라는 뜻이다.
        # 첫 조건을 통과했으니 여기서는 sources 항목이 존재한다는 것을 안다.
        # case["sources"]로 그 항목의 값을 꺼낸다.
        # 빈 리스트 []는 조건식에서 거짓으로 취급하고, not을 붙이면 참이 된다.
        # 즉 "출처 목록이 비었는가?"라는 검사이다. F03이 여기에 해당한다.
        elif not case["sources"]:
            kind = "evidence"  # TODO: 출처 목록이 비어 있으면 "evidence"
        # 앞 두 조건에 해당하지 않으면 출처 목록에 뭔가 들어 있다는 뜻이다.
        # 이번에는 답변 문장과 원본 문장을 꺼내 비교한다. !=는 "다르다"이다.
        # F01은 "공용 서버"와 "개인 폴더"가 다르므로 이 조건이 참이다.
        elif case["answer"] != case["source"]:
            kind = "factual_mismatch"  # TODO: 제공 원본과 내용이 다르면 "factual_mismatch"
        # 위 조건이 모두 거짓이면 이 예제에서는 ok라고 표시한다.
        # 현재 세 사례에는 ok가 없다. ok도 실제 사실성을 보장하는 인증은 아니다.
        else:
            kind = "ok"
        # append는 리스트 끝에 값 하나를 추가한다.
        # 이번 사례의 번호와 분류 이름을 딕셔너리 하나로 묶어 issues에 추가한다.
        # F01일 때 추가하는 값: {"id": "F01", "kind": "factual_mismatch"}.
        # 이 줄은 if/elif/else 바깥이므로 어느 분류가 나와도 매번 실행된다.
        issues.append({"id": case["id"], "kind": kind})
    # 반복이 끝나면 issues의 값은 다음과 같다.
    # [
    #     {"id": "F01", "kind": "factual_mismatch"},
    #     {"id": "F02", "kind": "format"},
    #     {"id": "F03", "kind": "evidence"},
    # ]
    # if/elif/else는 먼저 참이 된 조건 하나만 선택한다.
    # 따라서 한 사례에 문제가 여러 개 있어도 이 코드는 첫 문제 하나만 기록한다.
    # END D20-07-B01

    # TODO D20-07-B02: 사실성·형식·근거 검증을 서로 다른 검사라고 설명하세요.
    # 입력·대상: 제공된 F01/F02/F03 사례만 대상으로 분류합니다.
    # 완료 확인: outputs/review.json, review.md에서 사실 불일치/형식 누락/근거 누락을 확인합니다.
    # 주의: 사전 설계된 규칙 기반 점검이며 실제 생성형 AI의 진위 판정기가 아닙니다.
    # BEGIN D20-07-B02
    # [3단계] 문제 이름의 뜻을 함께 저장할 준비를 한다.
    # 아래 문장들은 실행할 명령이 아니라 사람이 읽을 설명이다.
    # format: 답변 양식에 꼭 있어야 하는 항목이 있는가?
    # evidence: 출처가 적혀 있는가? 그 자료가 근거로 적절한지도 별도로 봐야 한다.
    # factual_mismatch: 확인된 원본과 답변이 서로 어긋나는가?
    # 아래 설명에 출처의 적절성이 언급돼도 실제 코드는 목록이 비었는지만 검사한다.
    explanations = {
        "format": "JSON/응답에 필수 필드가 존재하는지 보는 구조 검증",           # TODO: JSON에 필수 필드가 있는지
        "evidence": "인용·출처 정보가 있는지와 적절한 근거인지 구분",         # TODO: 출처의 존재·적절성
        "factual_mismatch": "주장과 승인된 정답/원본이 모순되는지 사람·검증 규칙으로 확인", # TODO: 확인된 원본과 주장의 불일치
    }
    # END D20-07-B02
    # 아래는 후속 실습용 빈 보관함이다. 기본 단계에서 비어 있어도 정상이다.
    # {}는 빈 딕셔너리, []는 빈 리스트이다.
    # mitigation: 문제를 줄일 방법을 기록할 자리.
    mitigation={}
    # additional_checks: 추가 검사 항목들을 기록할 자리.
    additional_checks=[]
    # agent_case: AI가 도구를 사용하는 사례를 기록할 자리. 여기서는 실행하지 않는다.
    agent_case={}
    # trust_rules: 어떤 자료나 도구 동작을 신뢰할지 규칙을 적을 자리.
    trust_rules=[]

    # TODO D20-07-B03: 검증 결과와 향후 후속 수업 연결을 review.json 및 review.md로 저장하세요.
    # 입력·대상: 제공된 F01/F02/F03 사례만 대상으로 분류합니다.
    # 완료 확인: outputs/review.json, review.md에서 사실 불일치/형식 누락/근거 누락을 확인합니다.
    # 주의: 사전 설계된 규칙 기반 점검이며 실제 생성형 AI의 진위 판정기가 아닙니다.
    # BEGIN D20-07-B03
    # [4단계] 결과를 파일 두 개로 저장한다. 먼저 JSON용 데이터를 모은다.
    # report는 딕셔너리이다. "항목 이름": 값 형태로 보관한다.
    report = {
        # 왼쪽은 저장할 이름, 오른쪽 issues는 위에서 만든 결과 리스트 전체이다.
        "classification": issues,
        # 분류 이름들의 뜻을 모아 둔 설명 딕셔너리이다.
        "definitions": explanations,
        # 아래 네 항목은 후속 실습용이라 현재 {}, [], {}, []가 들어간다.
        "mitigation": mitigation,
        "checks": additional_checks,
        "agent_case": agent_case,
        "trust_rules": trust_rules,
        # 이 결과를 실제 자동 사실 검사로 오해하지 않도록 설명도 저장한다.
        "disclaimer": "교육용 규칙이며 실제 LLM 사실성 자동 판정 아님",
    }
    # Path의 /는 폴더와 파일 경로를 이어 붙인다. 숫자 나눗셈이 아니다.
    # 이 main.py가 있는 폴더 아래 outputs/review.json으로 저장한다.
    # write_json은 필요하면 폴더를 만들고 report를 JSON 형식의 글로 변환해 저장한다.
    # JSON은 딕셔너리처럼 항목 이름과 값을 적는 파일 형식이다.
    write_json(HERE / "outputs" / "review.json", report)
    # 이번에는 사람이 읽을 문서를 만든다.
    # lines는 문서에 쓸 글을 한 줄씩 담은 리스트이다.
    # Markdown에서 #으로 시작하는 글은 큰 제목으로 표시된다.
    # ""는 내용 없는 줄이다. 나중에 줄바꿈으로 연결하면 빈 줄이 된다.
    lines = ["# LLM 답변 검증 결과", "", "교육용 사례의 분류 결과", ""]
    # TODO: issues를 순회하여 F01~F03의 kind를 한 줄씩 기록
    # 오른쪽은 결과 한 개마다 문장 한 줄을 만들어 리스트로 모으는 코드이다.
    # for row in issues: 결과 딕셔너리를 하나씩 row에 넣는다.
    # row['id']와 row['kind']: 그 딕셔너리에서 번호와 문제 이름을 꺼낸다.
    # f"...{값}..."은 중괄호 자리에 실제 값을 넣어 문자열을 만든다.
    # 첫 문장: " - F01: factual_mismatch".
    # Markdown에서는 -로 시작하는 줄이 목록 항목으로 표시된다.
    # lines += [...]는 새 문장들을 기존 lines 뒤에 하나씩 덧붙인다.
    # 풀어 쓰면 다음과 같다.
    # for row in issues:
    #     sentence = f" - {row['id']}: {row['kind']}"
    #     lines.append(sentence)
    lines += [f" - {row['id']}: {row['kind']}" for row in issues] 
    # 문서 끝에 다른 수업 내용과의 연결을 설명하는 글을 덧붙인다.
    # ##은 작은 제목이다. 아래 문장은 설명일 뿐 실제 서버/DB를 실행하지 않는다.
    # FastAPI: 요청과 응답이 정해진 양식인지 확인하는 데 쓸 수 있다.
    # PostgreSQL: 비교 기준이 되는 원본 자료를 보관하는 데 쓸 수 있다.
    # RAG: 답변을 만들 때 참고할 자료를 찾아 제공하는 방식이다.
    # Agent: 도구로 작업하는 AI이며, 어떤 동작을 허용할지도 정해야 한다.
    lines += ["", "## 플랫폼 연결", "FastAPI: 입력·출력 계약 / PostgreSQL: 원본 / RAG: 검색 근거 / Agent: 도구 권한(후속)"]  # TODO: FastAPI·DB·RAG·Agent의 역할 기록
    # "\n"은 줄바꿈 문자이다.
    # "\n".join(lines)는 리스트의 문장들 사이에 줄바꿈을 넣어 긴 글 하나로 만든다.
    # 예: ["첫 줄", "둘째 줄"] → "첫 줄\n둘째 줄".
    # 마지막 + "\n"은 문서 끝에도 줄바꿈 하나를 붙인다.
    # write_md는 이 글을 outputs/review.md 파일로 저장한다.
    # print가 없어서 정상 실행해도 화면에 완료 메시지는 뜨지 않는다. 파일을 확인하자.
    write_md(HERE / "outputs" / "review.md", "\n".join(lines) + "\n")
    # END D20-07-B03

# 이 파일을 직접 실행했을 때만 아래 main()을 실행한다.
