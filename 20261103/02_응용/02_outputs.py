"""
실습 A02: RNN을 이용한 Many-to-One과 Many-to-Many 비교

[핵심 개념]

1. RNN (순환 신경망)
   - 순서가 있는 데이터를 처리하는 신경망이다.
   - 각 시점의 데이터를 순서대로 처리하면서 은닉 상태를 만든다.

2. Hidden (은닉 상태)
   - RNN이 데이터를 처리하면서 만들어 내는 내부 정보이다.
   - 여기서는 각 시점마다 8개의 은닉 특성을 만든다.

3. Linear (선형 변환 층)
   - 입력 특성의 개수를 원하는 출력 개수로 변환하는 층이다.
   - nn.Linear(8, 2)는 8개 특성을 2개 점수로 변환한다.
   - 여기서는 분류에 사용할 클래스 점수를 생성한다.

4. Many-to-One
   - 여러 시점의 데이터를 처리하고 최종 결과 하나를 만든다.
   - 여기서는 마지막 시점의 출력만 Linear 층에 전달한다.
   - 자료 하나당 클래스 점수 2개가 생성된다.

5. Many-to-Many
   - 여러 시점의 데이터를 처리하고 각 시점마다 결과를 만든다.
   - 여기서는 모든 시점의 출력을 Linear 층에 전달한다.
   - 자료 하나의 각 시점마다 클래스 점수 2개가 생성된다.

6. Logits (로짓)
   - 분류 모델이 출력하는 클래스별 점수이다.
   - 아직 확률로 변환된 값은 아니다.

7. torch.allclose()
   - 두 텐서의 값이 거의 같은지 비교하는 함수이다.
   - 여기서는 Many-to-Many의 마지막 시점 결과와
     Many-to-One의 결과가 같은지 확인한다.

[이번 실습의 목표]
같은 RNN과 Linear 층을 사용하더라도
마지막 시점만 사용하면 Many-to-One,
모든 시점을 사용하면 Many-to-Many가 된다는 것을 확인한다.
"""

import torch
from torch import nn

# 작은 CPU 실습의 실행 조건을 고정한다.
torch.set_num_threads(1)
torch.manual_seed(42)

from pathlib import Path
import pandas as pd

# --------------------------------------------------
# 1. 입력 데이터와 모델 생성
# --------------------------------------------------

# torch.randn(4, 6, 3)
#
# 데이터 형태: [B, T, F]
# B = Batch(자료 개수): 4
# T = Time(시점 개수): 6
# F = Feature(특성 개수): 3
#
# 자료 4개에 각각 6개의 시점이 있고,
# 각 시점마다 3개의 특성이 존재한다.
x = torch.randn(4, 6, 3)

# RNN 모델 생성
#
# 첫 번째 인자 3: 입력 특성 개수
# 두 번째 인자 8: 은닉 특성 개수
# batch_first=True: 데이터 형태를 [B, T, F]로 사용한다.
core = nn.RNN(3, 8, batch_first=True)

# Linear 층 생성
#
# 입력 특성 8개를 출력 점수 2개로 변환한다.
# 두 개의 클래스에 대한 점수를 만들기 위한 층이다.
head = nn.Linear(8, 2)

# --------------------------------------------------
# 2. RNN으로 모든 시점의 은닉 상태 생성
# --------------------------------------------------

# RNN에 입력 데이터를 전달한다.
#
# output:
# 모든 시점의 은닉 상태를 반환한다.
# 형태: [4, 6, 8]
#
# h:
# 마지막 시점의 은닉 상태를 반환한다.
# 형태: [1, 4, 8]
#
# 이번 실습에서는 output을 이용해 두 가지 방식을 비교한다.
output, h = core(x)

# --------------------------------------------------
# 3. Many-to-One 방식
# --------------------------------------------------

# output[:, -1]
#
# 첫 번째 차원(:): 자료 전체를 선택한다.
# 두 번째 차원(-1): 마지막 시점만 선택한다.
#
# 기존 output 형태: [4, 6, 8]
# 마지막 시점 선택 후: [4, 8]
#
# 마지막 시점의 은닉 상태만 Linear 층에 전달한다.
#
# 결과 형태: [4, 2]
# 자료 4개 각각에 대해 클래스 점수 2개가 생성된다.
many_to_one = head(output[:, -1])

# --------------------------------------------------
# 4. Many-to-Many 방식
# --------------------------------------------------

# output 전체를 Linear 층에 전달한다.
#
# output 형태: [4, 6, 8]
#
# Linear 층은 마지막 차원에 적용된다.
# 즉, 각 시점의 은닉 특성 8개를 점수 2개로 변환한다.
#
# 결과 형태: [4, 6, 2]
# 자료 4개 각각의 6개 시점마다 클래스 점수 2개가 생성된다.
#
# 같은 head를 모든 시점에 사용한다.
many_to_many = head(output)

# --------------------------------------------------
# 5. 결과 확인
# --------------------------------------------------

# Many-to-One과 Many-to-Many의 결과 형태를 출력한다.
print(
    "one:", tuple(many_to_one.shape),
    "many:", tuple(many_to_many.shape)
)

# Many-to-Many의 마지막 시점 결과와
# Many-to-One의 결과가 같은지 비교한다.
#
# many_to_many[:, -1]:
# 모든 자료에서 마지막 시점의 클래스 점수를 가져온다.
#
# many_to_one:
# 마지막 시점의 은닉 상태를 이용해 만든 클래스 점수이다.
#
# 같은 RNN 출력과 같은 Linear 층을 사용했으므로
# 두 결과가 일치하는지 확인할 수 있다.
print(
    "마지막 logits 일치:",
    torch.allclose(many_to_many[:, -1], many_to_one)
)

# 같은 Linear 층을 각 시점에 재사용한다.
# 다만 각 시점의 점수를 학습에 활용하려면
# 시점별 정답 데이터도 별도로 준비해야 한다.
print("같은 Head를 시점마다 재사용하며, 시점별 정답은 별도 설계가 필요하다.")