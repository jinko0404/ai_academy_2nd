"""
실습 B02: RNN의 마지막 은닉 상태를 이용한 분류 점수 생성

[핵심 개념]

1. RNN (Recurrent Neural Network, 순환 신경망)
   - 순서가 있는 데이터를 처리하는 신경망이다.
   - 이전 시점의 정보를 다음 시점으로 전달하면서 데이터를 처리한다.
   - 예: 문장, 음성, 시간에 따른 센서 데이터

2. 은닉 상태 (Hidden State)
   - RNN이 데이터를 처리하면서 내부적으로 만들어 내는 정보이다.
   - 이전 시점까지 처리한 정보를 다음 시점으로 전달하는 역할을 한다.
   - 여기서는 은닉 특성의 개수를 8개로 설정한다.

3. output과 h_n
   - output: 모든 시점에서 만들어진 은닉 상태를 반환한다.
   - h_n: RNN의 마지막 시점에서 만들어진 은닉 상태를 반환한다.
   - 둘 다 RNN이 처리한 결과이지만 반환하는 범위가 다르다.

4. nn.Linear (선형 변환 층)
   - 입력 데이터를 원하는 개수의 출력값으로 변환하는 층이다.
   - nn.Linear(8, 2)는 입력 8개를 출력 2개로 변환한다.
   - 여기서는 두 가지 클래스에 대한 점수를 만든다.

5. Logits (로짓)
   - 모델이 분류를 위해 출력하는 점수이다.
   - 아직 확률로 변환된 값은 아니다.
   - 값이 높은 클래스일수록 모델이 해당 클래스로 판단하는 점수가 높다.

[이번 실습의 목표]
RNN으로 순서가 있는 데이터를 처리하고,
마지막 은닉 상태 8개를 Linear 층에 전달하여
두 클래스의 분류 점수를 생성한다.
"""

import torch
from torch import nn

# 작은 CPU 실습의 실행 조건을 고정한다.
torch.set_num_threads(1)
torch.manual_seed(42)

# --------------------------------------------------
# 1. 입력 데이터 생성
# --------------------------------------------------

# torch.randn(4, 6, 3)
# 평균 0, 표준편차 1인 정규분포에서 임의의 값을 생성한다.
#
# 데이터 형태: [4, 6, 3]
# 4 = 자료 개수 (Batch)
# 6 = 각 자료의 시점 개수 (Sequence Length)
# 3 = 각 시점의 특성 개수 (Feature)
#
# 예: 자료 4개에 각각 6개의 시점이 있고,
# 각 시점마다 3개의 특성 데이터가 존재한다.
x = torch.randn(4, 6, 3)

# --------------------------------------------------
# 2. RNN 모델 생성 및 데이터 처리
# --------------------------------------------------

# nn.RNN(3, 8, batch_first=True)
#
# 첫 번째 인자 3:
# 입력 데이터의 특성 개수 (input_size)
#
# 두 번째 인자 8:
# RNN이 만들어 낼 은닉 특성의 개수 (hidden_size)
#
# batch_first=True:
# 입력 데이터의 형태를 [자료 개수, 시점, 특성]으로 설정한다.
rnn = nn.RNN(3, 8, batch_first=True)

# RNN에 입력 데이터를 전달한다.
#
# output:
# 모든 시점에서 만들어진 은닉 상태를 반환한다.
# 형태: [4, 6, 8]
#
# h_n:
# 마지막 시점의 은닉 상태를 반환한다.
# 형태: [1, 4, 8]
#
# 맨 앞의 1은 RNN 층의 개수이다.
output, h_n = rnn(x)

# --------------------------------------------------
# 3. Linear 층 생성
# --------------------------------------------------

# RNN의 은닉 특성 8개를 두 클래스의 점수 2개로 변환한다.
#
# nn.Linear(8, 2)
# 입력 특성 8개 → 출력 특성 2개
#
# bias=True는 기본값이므로 별도로 작성하지 않아도 된다.
head = nn.Linear(8, 2)

# --------------------------------------------------
# 4. 마지막 은닉 상태를 이용해 분류 점수 생성
# --------------------------------------------------

# h_n[-1]
# 마지막 RNN 층의 은닉 상태를 가져온다.
#
# h_n의 형태: [1, 4, 8]
# h_n[-1]의 형태: [4, 8]
#
# head에 전달하면 Linear 층이 8개 특성을 2개 점수로 변환한다.
#
# logits 형태: [4, 2]
# 자료 4개 각각에 대해 두 클래스의 점수가 만들어진다.
logits = head(h_n[-1])

# --------------------------------------------------
# 5. 결과 확인
# --------------------------------------------------

# 입력 데이터의 형태를 출력한다.
print("입력:", tuple(x.shape))

# 모든 시점의 출력과 마지막 은닉 상태의 형태를 출력한다.
print("output / h_n:", tuple(output.shape), tuple(h_n.shape))

# 두 클래스에 대한 분류 점수의 형태를 출력한다.
print("logits:", tuple(logits.shape))

# output의 마지막 시점과 h_n의 마지막 층 상태가 같은지 확인한다.
#
# output[:, -1]:
# 모든 자료에서 마지막 시점의 은닉 상태를 가져온다.
#
# h_n[-1]:
# 마지막 RNN 층의 은닉 상태를 가져온다.
#
# torch.allclose():
# 두 텐서의 값이 거의 같은지 확인한다.
print("마지막 시점 일치:", torch.allclose(output[:, -1], h_n[-1]))