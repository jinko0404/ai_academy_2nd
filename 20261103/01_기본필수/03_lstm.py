"""
============================================================
[실습 B03] LSTM을 이용한 시계열 데이터 예측 - 사전 개념 정리
============================================================

1. 시계열 데이터(Time Series)
   - 시간의 흐름에 따라 순서대로 기록된 데이터
   - 예: 날짜별 주가, 시간별 기온, 일별 매출
   - 과거 데이터를 이용해 미래의 값을 예측하는 데 사용한다.
   - 일반적인 데이터와 달리 데이터가 발생한 시간 순서가 중요하다.

2. 학습 데이터(Train)와 검증 데이터(Valid)
   - Train: 모델이 패턴을 학습하는 데 사용하는 데이터
   - Valid: 학습한 모델이 새로운 데이터에서도 예측을 잘하는지 확인하는 데이터
   - 시계열 데이터는 미래 정보가 과거 학습에 섞이지 않도록
     시간 순서를 고려해서 데이터를 분리해야 한다.
   - Test 데이터는 최종 성능 확인을 위한 데이터로,
     이번 실습에서는 모델 입력에 사용하지 않는다.

3. 슬라이딩 윈도우(Sliding Window)
   - 긴 시계열 데이터를 일정한 길이의 작은 묶음으로 나누는 방법
   - 예를 들어 관측값이 다음과 같다고 가정한다.
       [10, 20, 30, 40, 50, 60, 70, ...]
   - 과거 12개를 입력으로 사용하고 그다음 1개를 정답으로 사용한다.
   - 다음 묶음은 한 칸 이동해서 다시 만든다.
   - 이렇게 여러 개의 학습 데이터를 만들 수 있다.

4. LSTM(Long Short-Term Memory)
   - RNN 계열의 순환 신경망이다.
   - 데이터를 한 시점씩 순서대로 전달하면서 이전 정보와
     현재 정보를 이용해 새로운 은닉 상태를 만든다.
   - 일반적인 RNN보다 긴 시간의 정보를 기억하는 데 유리하도록
     설계된 구조다.
   - 시계열 데이터나 문장처럼 순서가 중요한 데이터를 처리한다.

5. LSTM의 입력 데이터 구조
   - batch_first=True로 설정하면 입력 형태는 다음과 같다.
   - [Batch, Time, Feature]

   - Batch: 한 번에 처리하는 데이터 묶음의 개수
   - Time: 각 데이터 묶음에 포함된 시간 단계의 개수
   - Feature: 각 시간 단계에서 사용하는 데이터의 특성 개수

   - 이번 실습은 과거 12개 관측값을 사용하고,
     각 관측값은 숫자 1개이므로 Feature는 1이다.

6. LSTM의 반환값
   - LSTM은 output과 (h_n, c_n)을 반환한다.

   - output:
     모든 시간 단계의 은닉 상태를 반환한다.
     각 시점에서 LSTM이 계산한 결과를 모아둔 것이다.

   - h_n:
     마지막 시간 단계의 은닉 상태를 반환한다.
     여러 층의 LSTM을 사용한다면 각 층의 마지막 은닉 상태가 담긴다.

   - c_n:
     마지막 시간 단계의 셀 상태를 반환한다.
     LSTM이 장기적인 정보를 관리하는 데 사용하는 내부 상태다.

   - 은닉 상태(h_n)와 셀 상태(c_n)는 서로 다른 개념이다.
     h_n은 출력에 사용되는 상태이고,
     c_n은 LSTM 내부에서 정보를 관리하는 상태다.

7. Linear 층(nn.Linear)
   - 신경망의 입력 데이터를 원하는 출력 형태로 변환하는 층이다.
   - 이번 실습에서는 LSTM이 만든 은닉 상태를 입력받아
     다음 시점의 숫자 하나를 예측하도록 사용한다.
   - 입력 특성 수와 출력 특성 수를 지정해서 만든다.

8. 예측값(Prediction)과 정답(Target)
   - Prediction: 모델이 계산한 예측값
   - Target(y): 실제 정답 데이터
   - 두 값을 비교해서 모델이 얼마나 잘 예측했는지 평가한다.

9. MSE(Mean Squared Error, 평균 제곱 오차)
   - 예측값과 실제 정답의 차이를 제곱한 뒤 평균을 구하는 평가 방법
   - 값이 작을수록 예측값과 정답의 차이가 작다는 의미다.
   - 이번 실습에서는 학습 전 예측 성능을 확인한다.

============================================================
[이번 문제에서 알아야 할 핵심]
============================================================

- 시계열 데이터는 시간 순서가 중요하다.
- Sliding Window로 과거 관측값과 다음 정답을 묶는다.
- LSTM은 순서가 있는 데이터를 처리한다.
- output에는 모든 시점의 은닉 상태가 담긴다.
- 마지막 시점의 은닉 상태를 이용하면 전체 입력 구간을
  바탕으로 다음 값 하나를 예측할 수 있다.
- Linear 층은 LSTM의 은닉 상태를 예측값으로 변환한다.
"""

import torch
from torch import nn

# 작은 CPU 실습의 실행 조건을 고정한다.
torch.set_num_threads(1)

# 난수 시드를 고정하여 실행할 때 같은 초기 난수를 사용하도록 한다.
torch.manual_seed(42)

from pathlib import Path
import pandas as pd

# 현재 Python 파일이 위치한 폴더 경로를 가져온다.
ROOT = Path(__file__).resolve().parent

# 현재 폴더에 있는 series.csv 파일을 읽어 DataFrame으로 저장한다.
df = pd.read_csv(ROOT / "series.csv")

# 시간 구간을 먼저 분리한다.
# Test 구간은 이번 실습에서 모델 입력으로 사용하지 않는다.

# split 열의 값이 train인 행에서 value 열의 데이터만 가져온다.
# 가져온 데이터를 PyTorch 텐서로 변환하고 자료형을 float32로 지정한다.
train = torch.tensor(
    df.loc[df["split"] == "train", "value"].values,
    dtype=torch.float32
)

# split 열의 값이 valid인 행에서 value 열의 데이터만 가져온다.
# 검증 데이터 역시 PyTorch 텐서로 변환한다.
valid = torch.tensor(
    df.loc[df["split"] == "valid", "value"].values,
    dtype=torch.float32
)

# ------------------------------------------------------------
# 1. Sliding Window 생성
# ------------------------------------------------------------

# unfold(0, 13, 1)
# 0: 첫 번째 차원인 시간 방향으로 데이터를 나눈다.
# 13: 한 묶음에 총 13개의 데이터를 포함한다.
# 1: 다음 묶음을 만들 때 한 칸씩 이동한다.
#
# 과거 관측값 12개 + 다음 정답값 1개로 구성한다.
# 예: [1, 2, 3, ..., 12, 13]
#     [2, 3, 4, ..., 13, 14]
#
# 이렇게 여러 개의 학습 데이터 묶음을 만든다.
window = train.unfold(0, 13, 1)

# 각 묶음에서 앞의 12개 데이터를 가져온다.
# unsqueeze(-1)은 마지막에 차원 하나를 추가한다.
#
# LSTM 입력 형태:
# [Batch, Time, Feature]
#
# Feature가 1인 이유는 각 시점에서 사용하는 값이 하나이기 때문이다.
x = window[:, :12].unsqueeze(-1)

# 각 묶음에서 마지막 1개 데이터를 정답으로 가져온다.
# 즉, 앞의 12개 데이터를 보고 예측해야 하는 다음 값이다.
y = window[:, 12:13]

# ------------------------------------------------------------
# 2. LSTM 모델 생성
# ------------------------------------------------------------

# LSTM(1, 8)
# 1: 입력 데이터의 특성 개수(Feature)
# 8: LSTM의 은닉 상태 크기(Hidden Size)
#
# batch_first=True:
# 입력 데이터의 첫 번째 차원을 Batch로 사용한다.
# 입력 형태는 [Batch, Time, Feature]가 된다.
lstm = nn.LSTM(1, 8, batch_first=True)

# Linear(8, 1)
# 입력 특성 8개를 출력값 1개로 변환한다.
#
# LSTM에서 나온 은닉 출력 8개를 받아
# 다음 시점의 숫자 하나를 예측하는 역할을 한다.
head = nn.Linear(8, 1)

# ------------------------------------------------------------
# 3. LSTM에 데이터 입력
# ------------------------------------------------------------

# x를 LSTM에 입력한다.
#
# output:
# 모든 시간 단계의 은닉 출력을 반환한다.
#
# h_n:
# 마지막 시간 단계의 은닉 상태를 반환한다.
#
# c_n:
# 마지막 시간 단계의 셀 상태를 반환한다.
#
# output 형태: [Batch, Time, Hidden]
# h_n 형태: [Layer, Batch, Hidden]
# c_n 형태: [Layer, Batch, Hidden]
output, (h_n, c_n) = lstm(x)

# ------------------------------------------------------------
# 4. 다음 시점의 값 예측
# ------------------------------------------------------------

# output[:, -1, :]
# 첫 번째 : 모든 Batch를 선택한다.
# 두 번째 -1: 마지막 시간 단계를 선택한다.
# 세 번째 : 모든 Hidden 특성을 선택한다.
#
# 과거 12개 관측값을 처리한 마지막 시점의 은닉 출력을 가져온다.
#
# 가져온 은닉 출력 8개를 Linear 층에 전달한다.
# Linear 층은 8개의 값을 이용해 다음 시점의 값 1개를 예측한다.
prediction = head(output[:, -1, :])

# ------------------------------------------------------------
# 5. 결과 확인
# ------------------------------------------------------------

# 입력 데이터와 정답 데이터의 형태를 출력한다.
print("입력 / 정답:", tuple(x.shape), tuple(y.shape))

# LSTM의 마지막 은닉 상태와 셀 상태의 형태를 출력한다.
print("h_n / c_n:", tuple(h_n.shape), tuple(c_n.shape))

# 모델이 예측한 결과의 형태를 출력한다.
print("예측:", tuple(prediction.shape))

# 첫 번째 데이터 묶음의 예측값을 출력한다.
# item()은 텐서에 들어 있는 숫자 하나를 일반 Python 숫자로 변환한다.
# round(..., 6)은 소수점 6자리까지 표시한다.
print("첫 예측:", round(prediction[0].item(), 6))

# MSELoss:
# 예측값(prediction)과 실제 정답(y)의 차이를 제곱하여 평균을 구한다.
#
# 학습 전 MSE이므로 아직 모델의 가중치를 업데이트하지 않은 상태다.
# 값이 작을수록 현재 예측값과 실제 정답의 차이가 작다는 의미다.
print("학습 전 MSE:", round(nn.MSELoss()(prediction, y).item(), 6))