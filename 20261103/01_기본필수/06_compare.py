import torch
from torch import nn

"""
============================================================
[개념 정리] RNN과 LSTM (순환 신경망)
============================================================

1. Sequence (시퀀스)
   - 순서가 있는 연속적인 데이터
   - 예: 주가, 날씨, 문장, 시간에 따른 센서 데이터

2. RNN (Recurrent Neural Network)
   - 이전 시점의 정보를 다음 시점으로 전달하는 신경망
   - 순서가 있는 데이터를 처리하는 데 사용한다.
   - 과거 정보를 은닉 상태(Hidden State)에 저장한다.
   - 긴 시퀀스에서는 기울기 소실 문제가 발생할 수 있다.

3. LSTM (Long Short-Term Memory)
   - RNN의 장기 의존성 문제를 보완한 신경망
   - 중요한 정보를 오래 기억하고 불필요한 정보는 제거한다.
   - Hidden State(h)와 Cell State(c)를 사용한다.

4. Hidden State (h)
   - 현재까지 처리한 정보를 나타내는 은닉 상태
   - 다음 시점으로 전달되며 출력에도 사용된다.

5. Cell State (c)
   - LSTM이 장기적인 정보를 기억하기 위한 상태
   - 정보의 유지, 삭제, 추가를 조절한다.

6. Batch Size (B)
   - 한 번에 처리하는 데이터 묶음의 개수

7. Sequence Length (T)
   - 하나의 데이터에 포함된 시점의 개수
   - 여기서는 시퀀스 하나당 6개의 시점이 있다.

8. Input Feature (F)
   - 각 시점의 입력 데이터가 가진 특징의 개수
   - 여기서는 1개의 특징을 사용한다.

9. Hidden Size
   - RNN 또는 LSTM 내부에서 사용하는 은닉 상태의 차원
   - 여기서는 8을 사용한다.

10. output
    - 모든 시점의 은닉 상태를 반환한다.
    - batch_first=True인 경우 (B, T, Hidden Size)

11. h_n
    - 마지막 시점의 은닉 상태를 반환한다.
    - 마지막 시점의 정보를 요약한 값으로 사용할 수 있다.
    - RNN: (계층 수 * 방향 수, B, Hidden Size)

12. Logits (로짓)
    - 분류 모델이 출력하는 클래스별 점수
    - Softmax 적용 전의 값이다.
    - 값이 클수록 해당 클래스로 예측할 가능성이 높다.

13. Linear Layer (선형 계층)
    - 입력 특징을 원하는 출력 차원으로 변환하는 계층
    - 여기서는 8차원의 은닉 상태를 2개 클래스 점수로 변환한다.

14. CrossEntropyLoss
    - 분류 문제에서 예측값과 실제 정답의 차이를 계산하는 손실 함수
    - Logits와 정답 레이블을 입력으로 받는다.

15. Gradient (기울기)
    - 손실을 줄이기 위해 가중치를 어느 방향으로 얼마나 변경해야 하는지 나타내는 값

16. Backpropagation (역전파)
    - 손실을 기준으로 각 파라미터의 Gradient를 계산하는 과정
    - loss.backward()로 실행한다.

17. Optimizer (최적화 도구)
    - 계산된 Gradient를 이용하여 모델의 가중치를 갱신한다.
    - optimizer.step()으로 실행한다.

18. Epoch (에포크)
    - 전체 학습 데이터를 한 번 학습하는 단위
    - 여기서는 30번 반복 학습한다.

19. Accuracy (정확도)
    - 전체 예측 중 정답을 맞힌 비율
    - 정답 개수 / 전체 데이터 개수로 계산한다.

20. Validation Data (검증 데이터)
    - 학습에 사용하지 않고 모델의 예측 성능을 확인하는 데이터
    - 학습 데이터와 분리하여 사용한다.

============================================================
[코드 실행 및 해설]
============================================================
"""

torch.set_num_threads(1)
# CPU 연산에 사용할 스레드 수를 1개로 고정한다.

torch.manual_seed(42)
# 난수 시드를 고정하여 실행 결과를 재현할 수 있도록 한다.


# ------------------------------------------------------------
# 1. 학습 데이터 생성
# ------------------------------------------------------------

# 원리용 독립 Sequence 20개. 증가=1, 감소=0, 가운데 평균은 거의 같다.

g = torch.Generator().manual_seed(1203)
# 데이터 생성에 사용할 별도의 난수 생성기를 만든다.
# seed를 고정하여 동일한 노이즈가 생성되도록 한다.

y_all = torch.tensor([0, 1] * 10)
# 정답 레이블 생성
# 0과 1을 번갈아 10번씩 배치한다.
# 총 20개의 정답 데이터가 만들어진다.
#
# 0: 감소
# 1: 증가

base = torch.linspace(-1, 1, 6)
# -1부터 1까지 동일한 간격으로 6개의 숫자를 생성한다.
# 결과: [-1.0, -0.6, -0.2, 0.2, 0.6, 1.0]

x_all = torch.stack([(2*y-1)*base for y in y_all]).unsqueeze(-1)
# 각 정답 레이블에 따라 증가 또는 감소 시퀀스를 생성한다.
#
# (2*y-1)의 결과
# y=0이면 -1
# y=1이면  1
#
# 따라서 정답이 0이면 감소하는 시퀀스,
# 정답이 1이면 증가하는 시퀀스가 만들어진다.
#
# torch.stack(): 여러 시퀀스를 하나의 텐서로 결합한다.
# unsqueeze(-1): 마지막에 특징 차원을 추가한다.
#
# 최종 형태: (20, 6, 1)
# 20: 전체 데이터 개수
# 6: 시퀀스 길이
# 1: 입력 특징 개수

x_all = x_all + 0.03*torch.randn(20, 6, 1, generator=g)
# 각 데이터에 작은 무작위 노이즈를 추가한다.
# 완벽하게 규칙적인 데이터가 아닌 실제 데이터와 비슷한 형태를 만든다.


# ------------------------------------------------------------
# 2. 학습 데이터와 검증 데이터 분리
# ------------------------------------------------------------

x_train, y_train = x_all[:12], y_all[:12]
# 앞의 12개 데이터를 학습용으로 사용한다.

x_valid, y_valid = x_all[12:16], y_all[12:16]
# 다음 4개 데이터를 검증용으로 사용한다.

# 마지막 4개는 보관. 함수에 전달하지 않는다.
# 학습 및 검증에 사용하지 않는 별도 보관 데이터이다.


# ------------------------------------------------------------
# 3. RNN과 LSTM 비교 학습
# ------------------------------------------------------------

for kind in ["RNN", "LSTM"]:
    # RNN과 LSTM을 차례대로 실행한다.

    torch.manual_seed(42)
    # 두 모델이 동일한 난수 시드에서 시작하도록 설정한다.

    core = nn.RNN(1, 8, batch_first=True) if kind == "RNN" else nn.LSTM(1, 8, batch_first=True)
    # 모델 종류에 따라 RNN 또는 LSTM을 생성한다.
    #
    # 첫 번째 1: 입력 특징 차원
    # 두 번째 8: Hidden Size
    # batch_first=True: 입력 형태를 (Batch, Sequence, Feature)로 사용한다.
    #
    # 두 모델 모두 동일한 입력 및 은닉 차원을 사용한다.

    head = nn.Linear(8, 2)
    # 은닉 상태 8차원을 2개 클래스의 점수로 변환한다.
    # 0: 감소
    # 1: 증가

    parameters = list(core.parameters()) + list(head.parameters())
    # RNN 또는 LSTM과 Linear 계층의 학습 파라미터를 하나로 모은다.
    # 두 부분 모두 학습되어야 하므로 함께 등록한다.

    optimizer = torch.optim.Adam(parameters, lr=0.02)
    # Adam 최적화 알고리즘을 사용한다.
    # lr=0.02: 학습률을 설정한다.
    # 학습률은 가중치를 갱신하는 크기에 영향을 준다.


    # --------------------------------------------------------
    # 4. 모델 학습
    # --------------------------------------------------------

    for epoch in range(30):
        # 전체 학습 과정을 30번 반복한다.

        optimizer.zero_grad()
        # 이전 반복에서 계산된 Gradient를 초기화한다.
        # PyTorch는 기본적으로 Gradient를 누적하기 때문에 필요하다.

        output, _ = core(x_train)
        # 학습 데이터를 RNN 또는 LSTM에 전달한다.
        #
        # output: 모든 시점의 은닉 상태
        # _: 마지막 은닉 상태(h_n)
        # LSTM의 경우 (h_n, c_n)을 반환하지만 여기서는 사용하지 않는다.
        #
        # output 형태: (12, 6, 8)
        # 12: 학습 데이터 개수
        # 6: 시퀀스 길이
        # 8: 은닉 상태 차원

        loss = nn.CrossEntropyLoss()(head(output[:, -1]), y_train)
        # output[:, -1]: 모든 데이터의 마지막 시점 은닉 상태를 가져온다.
        #
        # 형태: (12, 8)
        #
        # head(): 8차원 은닉 상태를 2개 클래스의 Logits로 변환한다.
        #
        # Logits 형태: (12, 2)
        #
        # CrossEntropyLoss():
        # 예측 점수와 실제 정답을 비교하여 손실을 계산한다.
        #
        # y_train: 실제 정답 레이블
        # loss: 모델의 예측 오차

        # TODO B06: 손실의 gradient를 구한 뒤 모델과 head를 갱신한다.
        # backward가 gradient를 계산하고 optimizer.step이 가중치를 바꾼다.
        # BEGIN B06
        loss.backward()
        # 손실을 기준으로 각 파라미터의 Gradient를 계산한다.

        optimizer.step()
        # 계산된 Gradient를 이용하여 모델의 가중치를 갱신한다.
        # END B06


    # --------------------------------------------------------
    # 5. 검증 데이터로 예측
    # --------------------------------------------------------

    core.eval()
    head.eval()
    # 평가 모드로 전환한다.
    # 학습이 끝난 모델의 예측 결과를 확인한다.

    with torch.inference_mode():
        # 추론 모드로 실행하여 Gradient 계산을 비활성화한다.

        output, _ = core(x_valid)
        # 검증 데이터를 모델에 전달한다.
        # 학습 과정에서 사용하지 않은 데이터로 예측한다.

        pred = head(output[:, -1]).argmax(dim=1)
        # 마지막 시점의 은닉 상태를 Linear 계층에 전달한다.
        # argmax(dim=1): 클래스 점수가 가장 높은 인덱스를 선택한다.
        #
        # 결과:
        # 0이면 감소로 예측
        # 1이면 증가로 예측


    # --------------------------------------------------------
    # 6. 결과 출력
    # --------------------------------------------------------

    print(
        kind,
        "params:", sum(p.numel() for p in parameters),
        "valid 정답:", y_valid.tolist(),
        "예측:", pred.tolist(),
        "accuracy:", round((pred == y_valid).float().mean().item(), 3)
    )

    # kind: 현재 실행한 모델 종류 (RNN 또는 LSTM)
    #
    # sum(p.numel() for p in parameters):
    # 모델이 가진 전체 학습 파라미터 개수를 계산한다.
    #
    # y_valid.tolist():
    # 실제 정답 데이터를 리스트로 변환한다.
    #
    # pred.tolist():
    # 모델의 예측 결과를 리스트로 변환한다.
    #
    # (pred == y_valid):
    # 예측 결과와 실제 정답을 비교한다.
    # 정답이면 True, 틀리면 False가 된다.
    #
    # float().mean():
    # True와 False를 1과 0으로 변환한 뒤 평균을 계산한다.
    #
    # item():
    # 텐서에서 숫자 값을 추출한다.
    #
    # round(..., 3):
    # 정확도를 소수점 셋째 자리까지 반올림한다.