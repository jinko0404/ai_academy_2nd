
"""
[실습 개념: OpenCV를 이용한 이미지 읽기 및 저장]

1. OpenCV (Open Source Computer Vision)
   - 이미지와 영상 처리를 위한 컴퓨터 비전 라이브러리
   - Python에서는 cv2라는 이름으로 불러온다.

2. Image (이미지)
   - 컴퓨터에서는 이미지를 숫자로 이루어진 배열로 표현한다.
   - 각 숫자는 픽셀의 색상 정보를 나타낸다.

3. Pixel (픽셀)
   - 이미지 화면을 구성하는 가장 작은 점 단위
   - 각 픽셀은 색상 정보를 가지고 있다.

4. BGR (Blue, Green, Red)
   - OpenCV에서 사용하는 기본 색상 채널 순서
   - 일반적인 RGB와 달리 파랑(B), 초록(G), 빨강(R) 순서다.
   - 각 채널의 값은 일반적으로 0~255 범위다.
   - 0은 해당 색상이 없다는 의미이고 255는 가장 강한 값이다.

5. Shape (배열 형태)
   - 배열이 몇 개의 행, 열, 채널로 구성되어 있는지 나타낸다.
   - 컬러 이미지의 형태는 (높이, 너비, 채널 수)이다.
   - 예: (480, 640, 3)
     → 높이 480픽셀, 너비 640픽셀, 색상 채널 3개

6. dtype (Data Type)
   - 배열 내부에 저장된 데이터의 자료형
   - OpenCV에서 일반적인 컬러 이미지는 uint8을 사용한다.
   - uint8은 부호 없는 8비트 정수이며 0~255를 표현한다.

7. min() / max()
   - 이미지 배열에서 가장 작은 값과 가장 큰 값을 확인한다.
   - min(): 가장 어두운 채널 값
   - max(): 가장 밝은 채널 값
   - 이미지 전체의 모든 채널을 대상으로 계산한다.

8. imread()
   - 이미지 파일을 읽어서 NumPy 배열로 변환하는 OpenCV 함수
   - 기본값은 컬러 이미지(BGR)로 읽는다.
   - 파일을 읽지 못하면 None을 반환한다.

9. imwrite()
   - NumPy 배열에 저장된 이미지 데이터를 파일로 저장하는 함수
   - 저장에 성공하면 True, 실패하면 False를 반환한다.
   - 원본 파일을 자동으로 수정하지 않고 지정한 경로에 저장한다.

10. NumPy Array (넘파이 배열)
    - 숫자 데이터를 효율적으로 저장하고 계산하는 배열 자료구조
    - OpenCV는 이미지를 NumPy 배열 형태로 처리한다.
"""

# ============================================================
# 1. 라이브러리 불러오기
# ============================================================

from pathlib import Path  # 파일 및 폴더 경로를 편리하게 관리
import os                 # 현재 작업 폴더 변경 등 운영체제 기능 사용
import cv2                # OpenCV: 이미지 및 영상 처리 라이브러리
import numpy as np        # NumPy: 배열 및 수치 데이터 처리 라이브러리


# ============================================================
# 2. 현재 작업 폴더 설정
# ============================================================

# __file__:
# 현재 실행 중인 Python 파일의 경로
#
# resolve():
# 상대 경로를 절대 경로로 변환
#
# parent:
# 현재 Python 파일이 들어 있는 상위 폴더 경로
#
# os.chdir():
# 현재 작업 폴더를 변경한다.
#
# 이렇게 설정하면 다른 위치에서 프로그램을 실행하더라도
# 현재 Python 파일이 위치한 폴더를 기준으로 이미지를 찾는다.

os.chdir(Path(__file__).resolve().parent)


# ============================================================
# 3. 이미지 읽기
# ============================================================

# OpenCV의 imread():
# 이미지 파일을 읽어서 NumPy 배열로 변환한다.
#
# "scene.png":
# 현재 작업 폴더에 있는 이미지 파일
#
# flags를 생략했으므로 기본값인 컬러 이미지로 읽는다.
# OpenCV의 기본 색상 순서는 RGB가 아닌 BGR이다.
#
# 이미지 읽기에 성공하면 image에 이미지 배열이 저장된다.
# 실패하면 None이 반환된다.

# >>> TODO B01
image = cv2.imread("scene.png")
# <<< TODO B01


# ============================================================
# 4. 이미지 배열의 기본 정보 확인
# ============================================================

# shape:
# 이미지 배열의 크기와 차원을 확인한다.
#
# 컬러 이미지의 형태:
# (높이, 너비, 채널 수)
#
# 예: (480, 640, 3)
# 높이 480, 너비 640, BGR 색상 채널 3개

print("shape:", image.shape)


# dtype:
# 배열 내부에 저장된 데이터의 자료형을 확인한다.
#
# uint8:
# 0~255 범위의 정수를 저장하는 8비트 자료형
# 일반적인 이미지 픽셀 값에 사용된다.

print("dtype:", image.dtype)


# ============================================================
# 5. 이미지 픽셀 값의 최소값과 최대값 확인
# ============================================================

# min():
# 이미지 전체에서 가장 작은 픽셀 채널 값을 확인한다.
#
# max():
# 이미지 전체에서 가장 큰 픽셀 채널 값을 확인한다.
#
# int():
# NumPy의 정수 자료형 값을 일반 Python 정수로 변환한다.
#
# 참고:
# 여기서 확인하는 값은 이미지 전체의 B, G, R 채널을
# 모두 대상으로 계산한 최솟값과 최댓값이다.

print("min/max:", int(image.min()), int(image.max()))


# ============================================================
# 6. 특정 픽셀의 BGR 색상값 확인
# ============================================================

# image[30, 30]:
# 이미지의 30번째 행, 30번째 열에 있는 픽셀을 선택한다.
#
# 이미지 배열은 [행, 열] 순서로 접근한다.
# 따라서 [30, 30]은 세로 30번째, 가로 30번째 위치다.
#
# 해당 픽셀에는 B, G, R 값이 각각 저장되어 있다.
#
# tolist():
# NumPy 배열을 일반 Python 리스트로 변환한다.
#
# 예: [0, 0, 255]
# B=0, G=0, R=255이므로 빨간색이다.

print("빨강 패치의 BGR:", image[30, 30].tolist())


# ============================================================
# 7. 이미지 파일 저장
# ============================================================

# imwrite():
# 이미지 배열을 지정한 파일 형식으로 저장한다.
#
# "p01_copy.png":
# 저장할 파일 이름
#
# image:
# 저장할 이미지 배열
#
# saved:
# 저장 성공 여부를 Boolean 값으로 반환한다.
# True  = 저장 성공
# False = 저장 실패
#
# 원본 scene.png는 그대로 유지하고
# p01_copy.png라는 별도의 파일을 생성한다.

saved = cv2.imwrite("p01_copy.png", image)

print("PNG 저장:", saved)

